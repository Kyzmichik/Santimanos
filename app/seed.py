def seed_hints():
    """Додає підказки до категорій, де їх ще немає (адмін може змінити в панелі)."""
    changed = False
    for name, hint in HINTS.items():
        for cat in Category.query.filter_by(name=name, hint=None):
            cat.hint = hint
            changed = True
    if changed:
        db.session.commit()


def seed_defaults():
    """Одноразово (за версією) додає стандартні категорії та підказки.

    Після цього зміни адміна не перезаписуються: видалені категорії не повертаються.
    """
    meta = db.session.get(Meta, "seed")
    if meta and meta.value == SEED_VERSION:
        return
    seed_categories()
    seed_hints()
    if meta:
        meta.value = SEED_VERSION
    else:
        db.session.add(Meta(key="seed", value=SEED_VERSION))
    db.session.commit()
