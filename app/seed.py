SEED_VERSION = "categories-v2"


def seed_categories():
    """Додає відсутні категорії й підкатегорії, нічого не видаляючи й не перейменовуючи."""
    changed = False
    for parent_name, children in CATEGORIES.items():
        parent = Category.query.filter_by(name=parent_name, parent_id=None).first()
        if not parent:
            parent = Category(name=parent_name)
            db.session.add(parent)
            db.session.flush()
            changed = True
        existing = {c.name for c in parent.children}
        for name in children:
            if name not in existing:
                db.session.add(Category(name=name, parent_id=parent.id))
                changed = True
    if changed:
        db.session.commit()


